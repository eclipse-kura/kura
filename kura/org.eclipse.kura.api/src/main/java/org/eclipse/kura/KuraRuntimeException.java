package org.eclipse.kura;

import org.osgi.annotation.versioning.ProviderType;

/**
 * The {@link KuraRuntimeException} class is the superclass of all runtime exceptions in the Kura project. It extends
 * the JDK {@link RuntimeException} class by requesting its invokers to provide an error code when building its
 * instances. The code is one value of {@link KuraErrorCode}; the code is used to document the possible error conditions
 * generated by the platform as well as to identify the localized exception messages to be reported. Exceptions messages
 * are stored in the {@code KuraExceptionMessagesBundle} Properties Bundle and they are keyed on the exception code.
 *
 * @see KuraErrorCode
 *
 * @noextend This class is not intended to be subclassed by clients.
 */
@ProviderType
public class KuraRuntimeException extends RuntimeException {

    /** The Constant denoting serial version identifier. */
    private static final long serialVersionUID = -7202805328805688329L;

    /** The associated arguments. */
    private Object[] arguments;

    /** The associated error code. */
    private final KuraErrorCode code;

    /**
     * Builds a new {@link KuraRuntimeException} instance based on the supplied {@link KuraErrorCode}.
     *
     * @param code
     *            the error code
     */
    public KuraRuntimeException(final KuraErrorCode code) {
        this.code = code;
    }

    /**
     * Builds a new {@link KuraRuntimeException} instance based on the supplied {@link KuraErrorCode}.
     *
     * @param code
     *            the error code
     * @param arguments
     *            the arguments
     */
    public KuraRuntimeException(final KuraErrorCode code, final Object... arguments) {
        this.code = code;
        this.arguments = arguments;
    }

    /**
     * Builds a new {@link KuraRuntimeException} instance based on the supplied {@link KuraErrorCode}, an optional
     * Throwable cause, and optional arguments for the associated exception message.
     *
     * @param code
     *            the error code
     * @param cause
     *            the cause
     * @param arguments
     *            the arguments
     */
    public KuraRuntimeException(final KuraErrorCode code, final Throwable cause, final Object... arguments) {
        super(cause);
        this.code = code;
        this.arguments = arguments;
    }

    /**
     * Gets the error code.
     *
     * @return the error code
     */
    public KuraErrorCode getCode() {
        return this.code;
    }

    /** {@inheritDoc} */
    @Override
    public String getLocalizedMessage() {
        return KuraExceptionMessages.localizedMessage(this.code, this.arguments);
    }

    /** {@inheritDoc} */
    @Override
    public String getMessage() {
        return KuraExceptionMessages.message(this.code, this.arguments);
    }

}
